import { expect, test } from '@playwright/test'

test('AI 工作台演示可保存并带入草稿，厂商在确认发送前看不到项目', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/experience/dealer')
  const navigation = page.getByRole('navigation', { name: '工作台栏目' })
  const tab = navigation.getByRole('button', { name: 'AI 工作台' })
  await expect(tab.locator('svg')).toBeVisible()
  await tab.click()
  await expect(page.getByRole('heading', { name: 'AI 工作台' })).toBeVisible()
  await page.getByRole('button', { name: '用 AI 整理', exact: true }).click()
  await expect(page.getByLabel('员工人数')).toHaveValue('120')
  await expect(page.getByLabel('授权用户数')).toHaveValue('')
  await page.getByRole('button', { name: '确认需求并匹配' }).click()
  await expect(page.getByText('1 款可选')).toBeVisible()
  const product = page.locator('article').filter({ has: page.getByRole('heading', { name: '云序 ERP 专业版' }) })
  await product.getByText('查看厂商资料').click()
  await expect(product.getByText('演示软件目录', { exact: false })).toBeVisible()
  await product.getByRole('button', { name: '用此产品预览草稿' }).click()
  await expect(page.getByText(/授权席位：待确认/)).toBeVisible()
  await page.getByRole('button', { name: '保存询价草稿' }).click()
  await expect(page.getByText('已保存 · 未提交')).toBeVisible()
  await page.getByRole('button', { name: '打开项目', exact: true }).click()
  await expect(page.getByRole('heading', { name: '海川精工 · ERP 采购' })).toBeVisible()

  const project = new URL(page.url()).searchParams.get('project')
  expect(project).toBeTruthy()
  const vendor = await context.newPage()
  await vendor.goto('/experience/vendor?project=' + project)
  await expect(vendor.getByText('当前身份无法查看此项目')).toBeVisible()
  await expect(vendor.getByRole('navigation', { name: '工作台栏目' }).getByRole('button', { name: 'AI 工作台' })).toHaveCount(0)

  await page.getByRole('button', { name: '用 AI 整理需求' }).click()
  await expect(page.getByText('已保存 · 未提交')).toBeVisible()
  await page.getByRole('button', { name: '打开项目', exact: true }).click()
  await page.getByRole('button', { name: '提交厂商询价', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('询价产品')).toHaveValue('ERP-PRO')
  await expect(dialog.getByLabel('对厂商的询价摘要')).toHaveValue(/授权席位：待确认/)
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: '确认并提交询价' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(vendor.getByRole('heading', { name: /渠道采购项目/ })).toBeVisible()
  await expect(vendor.getByRole('definition').filter({ hasText: /授权席位：待确认/ })).toBeVisible()
})
